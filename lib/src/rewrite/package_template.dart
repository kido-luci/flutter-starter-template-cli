import '../package_spec.dart';

final RegExp _wordBoundary = RegExp(r'_+');

String packagePascalName(String name) => name
    .split(_wordBoundary)
    .where((part) => part.isNotEmpty)
    .map((part) => '${part[0].toUpperCase()}${part.substring(1)}')
    .join();

Map<String, String> reusablePackageFiles({
  required String name,
  required ReusablePackageType type,
  required List<String> dependencies,
}) {
  final pascal = packagePascalName(name);
  final serviceType = pascal.endsWith('Service') ? pascal : '${pascal}Service';
  final dependencyLines =
      dependencies.map((dep) => '  $dep: ^0.1.0').join('\n');
  final flutterDependency = type.usesFlutter
      ? '${dependencyLines.isEmpty ? '' : '$dependencyLines\n'}  flutter:\n    sdk: flutter'
      : dependencyLines;
  final testDependency = type.usesFlutter
      ? '  flutter_test:\n    sdk: flutter'
      : '  test: ^1.25.0';

  final source = switch (type) {
    ReusablePackageType.contracts => '''
/// Marker interface for contracts intentionally exposed by this package.
abstract interface class ${pascal}Contract {}
''',
    ReusablePackageType.infrastructure => '''
/// Public service boundary owned by the $name package.
abstract interface class $serviceType {
  Future<void> initialize();

  Future<void> dispose();
}
''',
    ReusablePackageType.platform => '''
import 'package:flutter/foundation.dart';

/// Immutable result exposed by the $name platform boundary.
@immutable
final class ${pascal}Availability {
  const ${pascal}Availability({required this.isAvailable});

  final bool isAvailable;
}
''',
    ReusablePackageType.ui => '''
import 'package:flutter/widgets.dart';

/// Layout-neutral host for reusable $name presentation content.
class ${pascal}Host extends StatelessWidget {
  const ${pascal}Host({required this.child, super.key});

  final Widget child;

  @override
  Widget build(BuildContext context) => child;
}
''',
    ReusablePackageType.dev => '''
/// Shared deterministic fixture metadata for tests and development tools.
final class ${pascal}Fixture {
  const ${pascal}Fixture(this.name);

  final String name;
}
''',
  };

  final test = type.usesFlutter
      ? '''
import 'package:flutter/widgets.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:$name/$name.dart';

void main() {
  testWidgets('public API is usable', (tester) async {
    ${type == ReusablePackageType.ui ? "await tester.pumpWidget(const ${pascal}Host(child: SizedBox()));" : "const value = ${pascal}Availability(isAvailable: true);\n    expect(value.isAvailable, isTrue);"}
  });
}
'''
      : '''
import 'package:$name/$name.dart';
import 'package:test/test.dart';

void main() {
  test('public API is available', () {
    ${type == ReusablePackageType.contracts ? "${pascal}Contract? value;\n    expect(value, isNull);" : type == ReusablePackageType.infrastructure ? "$serviceType? value;\n    expect(value, isNull);" : "expect(const ${pascal}Fixture('fixture').name, 'fixture');"}
  });
}
''';

  return {
    'pubspec.yaml': '''
name: $name
description: Reusable ${type.name} package generated by fst.
version: 0.1.0
publish_to: none
resolution: workspace

environment:
  sdk: ^3.12.0

dependencies:
${flutterDependency.isEmpty ? '  # No runtime dependencies.' : flutterDependency}

dev_dependencies:
$testDependency
  lints: ^4.0.0
''',
    'lib/$name.dart': "export 'src/$name.dart';\n",
    'lib/src/$name.dart': source.trimLeft(),
    'test/${name}_test.dart': test.trimLeft(),
  };
}
